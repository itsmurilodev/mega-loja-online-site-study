CREATE TABLE IF NOT EXISTS public.stores (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    city TEXT NOT NULL,
    zip_code TEXT NOT NULL,
    address TEXT NOT NULL,
    capacity INTEGER NOT NULL DEFAULT 20,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS public.products (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    image_url TEXT,
    sku TEXT,
    barcode TEXT
);

CREATE TABLE IF NOT EXISTS public.inventory (
    store_id INTEGER NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (store_id, product_id)
);

CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    customer_cpf TEXT,
    delivery_method TEXT NOT NULL,
    store_id INTEGER REFERENCES public.stores(id),
    product_id INTEGER NOT NULL REFERENCES public.products(id),
    quantity INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL,
    pickup_code TEXT,
    card_number_masked TEXT,
    payment_status TEXT DEFAULT 'aprovado',
    third_party_name TEXT,
    third_party_cpf TEXT,
    discount_coupon TEXT,
    refund_requested INTEGER DEFAULT 0,
    cancellation_reason TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    created_at TEXT NOT NULL
);

-- Índices para chaves estrangeiras e buscas frequentes
CREATE INDEX IF NOT EXISTS idx_inventory_product_id ON public.inventory(product_id);
CREATE INDEX IF NOT EXISTS idx_orders_store_id ON public.orders(store_id);
CREATE INDEX IF NOT EXISTS idx_orders_product_id ON public.orders(product_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_pickup_code ON public.orders(pickup_code);
CREATE INDEX IF NOT EXISTS idx_notifications_order_id ON public.notifications(order_id);

-- Row Level Security (RLS)
ALTER TABLE public.stores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "stores_access_policy" ON public.stores
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE POLICY "products_access_policy" ON public.products
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE POLICY "inventory_access_policy" ON public.inventory
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE POLICY "orders_access_policy" ON public.orders
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

CREATE POLICY "notifications_access_policy" ON public.notifications
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
