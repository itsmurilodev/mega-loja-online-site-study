-- Cartões atendidos:
--   S3-22 janela de retirada   -> orders.pickup_slot
--   S3-20 checkout misto       -> orders.shipping_address, orders.shipping_cost
--   S3-23 Pix / meios          -> orders.payment_method, orders.payment_detail
--   S3-25 transferência        -> orders.origin_store_id, orders.transfer_eta_days,
--                                 stores.kind, loja 99 (Centro de Distribuição)
--   S3-17 log de auditoria     -> tabela audit_log
-- O backend detecta sozinho se a migração já foi aplicada e, enquanto não for,
-- continua funcionando sem esses recursos.
