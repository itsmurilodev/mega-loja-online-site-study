-- ---------- orders ----------
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS pickup_slot TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS shipping_address TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS shipping_cost NUMERIC(10, 2) DEFAULT 0;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_method TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_detail TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS origin_store_id INTEGER; -- sem FK de propósito: evita embed ambíguo orders→stores no PostgREST
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS transfer_eta_days INTEGER;

CREATE INDEX IF NOT EXISTS idx_orders_pickup_slot ON public.orders(store_id, pickup_slot);
CREATE INDEX IF NOT EXISTS idx_orders_origin_store_id ON public.orders(origin_store_id);

-- ---------- stores: tipo (filial | cd) ----------
ALTER TABLE public.stores ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'filial';

-- Centro de Distribuição: não aparece na lista de filiais de retirada (active = 0),
-- mas tem estoque próprio e serve de origem para transferências.
INSERT INTO public.stores (id, name, city, zip_code, address, capacity, active, kind)
VALUES (99, 'Centro de Distribuição MegaLoja', 'Canoas', '92000-000', 'Av. Logística, 1000', 0, 0, 'cd')
ON CONFLICT (id) DO NOTHING;

-- Estoque inicial do CD: 50 unidades de cada produto (só onde ainda não existe).
INSERT INTO public.inventory (store_id, product_id, quantity)
SELECT 99, p.id, 50 FROM public.products p
ON CONFLICT (store_id, product_id) DO NOTHING;

-- ---------- audit_log (S3-17) ----------
CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE SET NULL,
    user_id TEXT,
    user_email TEXT,
    user_role TEXT,
    action TEXT NOT NULL,
    detail TEXT,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_log_order_id ON public.audit_log(order_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON public.audit_log(created_at);

ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;

-- Só a chave de serviço (backend) escreve/lê o log: sem policy para anon/authenticated.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'audit_log'
  ) THEN
    CREATE POLICY "audit_log_service_only" ON public.audit_log
      FOR ALL TO service_role USING (true) WITH CHECK (true);
  END IF;
END $$;
